TNR = 'ABCDEF+TimesNewRomanPSMT'   # так гарнитуру называет подмножество шрифта

A4_W, A4_H = 595.28, 841.89


def fonts(all_=None, body=None, aux=None, pagenum=None) -> dict:
    """Счётчики символов по (гарнитура, кегль) – то, что считает extractor."""
    return {
        'all':     all_ or {(TNR, 14.0): 5000},
        'body':    body or {(TNR, 14.0): 4000},
        'aux':     aux or {(TNR, 12.0): 300},
        'pagenum': pagenum or {(TNR, 14.0): 20},
    }


def margins(page: int, left=30, right=15, top=20, bottom=20) -> dict:
    """Поля одной страницы в том виде, в каком их меряет extractor: в точках
    и от краёв листа, а не в миллиметрах."""
    return {
        'page':   page,
        'page_w': A4_W,
        'page_h': A4_H,
        'x0':     left * PT_PER_MM,
        'x1':     A4_W - right * PT_PER_MM,
        'top':    top * PT_PER_MM,
        'bottom': A4_H - bottom * PT_PER_MM,
    }


def report(pages=None, title_page=1, task_page=2, font_info=None,
           margins_by_page=None, **overrides) -> dict:
    """Работа, готовая к check_gost.

    title_page и task_page – номера листов титульного раздела; None означает,
    что такого листа в работе нет. От них зависят и S2, и освобождение этих
    листов от проверки полей и кегля.
    """
    pages = list(PAGES if pages is None else pages)
    numbers = range(1, len(pages) + 1)
    data = {
        'path':            '/tmp/otchet.pdf',
        'filename':        'Иванов Иван Иванович.pdf',
        'text_by_page':    pages,
        'full_text':       '\n'.join(pages),
        'pages_count':     len(pages),
        'pages':           [{'page': n,
                             'is_title': n == title_page,
                             'is_task':  n == task_page,
                             'is_front': False} for n in numbers],
        'margins_by_page': [margins(n) for n in numbers]
                           if margins_by_page is None else margins_by_page,
        'font_info':       fonts() if font_info is None else font_info,
        'student':         {'name': 'Иванов Иван Иванович', 'group': 'ИВТ-201'},
        'images':          [],
        'is_scanned':      False,
        'error':           None,
    }
    data.update(overrides)
    return data


def replaced(old: str, new: str) -> list:
    """Страницы эталона с единственной заменой.

    Отсутствие фрагмента или его повтор – ошибка самого теста: работа молча
    осталась бы целой, и проверка «критерий провалился» ничего бы не значила.
    """
    hits = sum(page.count(old) for page in PAGES)
    if hits != 1:
        raise AssertionError(
            f'фрагмент {old!r} встречается в эталоне {hits} раз, нужен ровно один')
    return [page.replace(old, new) for page in PAGES]


def without(*page_indexes) -> list:
    """Страницы эталона без перечисленных листов."""
    drop = set(page_indexes)
    return [page for index, page in enumerate(PAGES) if index not in drop]
